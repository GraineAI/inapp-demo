// Firebase (the agent's calls ring through FCM on Android) needs composeApp/google-services.json, which is
// never committed. Without it the app still builds and runs; only push ringing is off.
if (file("google-services.json").exists()) {
    apply(plugin = "com.google.gms.google-services")
}

// Per-developer values from local.properties (git-ignored; see local.properties.example).
val local = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun setting(key: String, env: String, default: String): String =
    local.getProperty(key)?.takeIf { it.isNotBlank() } ?: System.getenv(env)?.takeIf { it.isNotBlank() } ?: default

/**
 * The shared use-case packs (the .json files in demo/usecases), bundled unchanged into the shared code as text, so
 * Android and iOS read the same files the same way. One copy for every platform: edit the packs there.
 */
val generatePacks by tasks.registering {
    val packs = rootProject.file("../usecases")
    val ids = listOf("health-coach", "banking-support", "retail-shopping")
    val out = layout.buildDirectory.dir("generated/usecases/kotlin")
    inputs.files(ids.map { packs.resolve("$it.json") }).withPathSensitivity(PathSensitivity.NAME_ONLY)
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile.resolve("ai/graine/demo/domain")
        dir.deleteRecursively()
        dir.mkdirs()
        val dollar = "$"
        val entries = ids.joinToString(",\n") { id ->
            val text = packs.resolve("$id.json").readText().replace(dollar, "$dollar{'$dollar'}")
            "    \"$id\" to \"\"\"$text\"\"\""
        }
        dir.resolve("BundledPacks.kt").writeText(
            "package ai.graine.demo.domain\n\n" +
                "/** The use-case packs (demo/usecases), bundled at build time. Generated by composeApp's generatePacks: never edit. */\n" +
                "internal val bundledPackTexts: Map<String, String> = mapOf(\n$entries,\n)\n"
        )
    }
}

